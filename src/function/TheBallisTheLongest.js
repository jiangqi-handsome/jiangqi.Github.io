/**
 * 求最长递增子序列的长度
 * 
 * 什么是最长递增子序列？
 * 答：给定一个整数数组 nums，找到其中最长的严格递增子序列的长度。
 * 
 * 比如：【10, 9, 2, 5, 3, 7, 101, 18】的最长递增子序列为[2, 3, 7, 101]，长度为4。
 * 
 * 简单点：[4, 5, 1, 2, 3]的最长递增子序列为[1, 2, 3]，长度为3，
 *        [4]选择  ======>  [4]
 *        [4, 5]选择  ======>  [4, 5]
 *        [4, 5, 1]选择  ======>  [1]
 *        [4, 5, 1, 2]选择  ======>  [1, 2]
 *        [4, 5, 1, 2, 3]选择  ======>  [1, 2, 3]
 * 
 *        最后的最长递增子序列为[1, 2, 3]，长度为3。
 * 
 *        有点像是一个选择题，选择一个最长的递增子序列。
 *        再细点：【10, 9, 2, 5, 3, 7, 101, 18】的最长递增子序列为[2, 3, 7, 101]，长度为4。
 * 
 * @param {number[]} nums - 输入的整数数组
 * @return {number} - 最长递增子序列的长度
 */

function lengthOfLIS(nums) {
    // 定义一个数组 dp，其中 dp[i] 表示以 nums[i] 结尾的最长递增子序列的长度
    const dp = new Array(nums.length).fill(1);

    // 遍历数组 nums
    for (let i = 1; i < nums.length; i++) {

        // 遍历 nums 中的前 i 个元素
        for (let j = 0; j < i; j++) {

            // 如果 nums[i] 大于 nums[j]
            if (nums[i] > nums[j]) {

                // 更新 dp[i]，取 dp[i] 和 dp[j] + 1 的最大值
                dp[i] = Math.max(dp[i], dp[j] + 1);
            }
        }
    }

    // 返回 dp 数组中的最大值，即最长递增子序列的长度
    return Math.max(...dp);
}

// 测试代码
// 创建一个整数数组 nums
const nums = [10, 9, 2, 5, 3, 7, 101, 18];

// 调用 lengthOfLIS 函数计算最长递增子序列的长度
const length = lengthOfLIS(nums);

console.log(length); // 输出: 4 (最长递增子序列为 [2, 3, 7, 101])